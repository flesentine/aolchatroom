function randomOf(items) {
  return items[Math.floor(Math.random() * items.length)];
}

function cityFromLocation(location) {
  return String(location || "").split(",")[0].trim();
}

export function detectTopics(text) {
  return TOPICS.filter((topic) => topic.re.test(text)).map((topic) => topic.id);
}

export function scoreCharacterForText(character, text) {
  const lower = String(text || "").toLowerCase();
  let score = character.personality.sociability * 1.5 + Math.random() * 0.8;
  if (lower.includes(character.name.toLowerCase())) score += 20;
  for (const topic of TOPICS) {
    if (!topic.re.test(text)) continue;
    for (const interest of topic.interests) {
      if (character.interests.some((item) => item.toLowerCase() === interest.toLowerCase())) score += 4;
    }
  }
  for (const interest of character.interests) {
    if (interest.length > 3 && lower.includes(interest.toLowerCase())) score += 5;
  }
  return score;
}

export function renderAmbient(character) {
  const families = ["random", "random_questions", ...(character.cannedFamilies || [])];
  const familyName = randomOf(families);
  const family = FAMILY[familyName] || FAMILY.random;
  return randomOf(family)
    .replaceAll("{city}", cityFromLocation(character.location))
    .replaceAll("{age}", String(character.age));
}

export function renderReaction(character, previousMessage) {
  const topics = detectTopics(previousMessage?.text || "");
  const topic = topics[0];
  if (topic && DIRECTED[topic]) return randomOf(DIRECTED[topic]);
  const roll = Math.random();
  if (character.personality.argumentative > 0.65 && roll < 0.35) return randomOf(FAMILY.disagree);
  if (character.personality.sarcasm > 0.65 && roll < 0.55) return randomOf(FAMILY.tease);
  if (character.personality.curiosity > 0.7 && roll < 0.60) return randomOf(FAMILY.random_questions);
  return randomOf(roll < 0.55 ? FAMILY.agree : FAMILY.random);
}

export function renderDirectedFallback(character, human) {
  const text = String(human?.text || "");
  const lower = text.toLowerCase();
  const sexLetter = character.sex === "female" ? "f" : character.sex === "male" ? "m" : "x";
  if (/\basl\b|age\/?sex\/?location/i.test(lower)) {
    return `${character.age}/${sexLetter}/${cityFromLocation(character.location)}`;
  }
  if (/where (are|r) (you|u) from|where.*from|what city|location\??/i.test(lower)) {
    return `im in ${character.location}`;
  }
  if (/how old|what age|age\??/i.test(lower)) return `im ${character.age}`;
  if (/what do (you|u) do|job\??|work\??/i.test(lower)) return `i work as a ${character.occupation}`;
  if (/^\s*(hi|hey|hello|yo|sup)\b/i.test(text)) return randomOf(["hey", "hi", "sup", "hey whats up", "yo"]);
  if (/anyone here\??|anybody here\??|is anyone here\??/i.test(lower)) return randomOf(["yeah", "im here", "lol yeah", "yep", "barely"]);

  const topics = detectTopics(text);
  for (const topic of topics) {
    if (DIRECTED[topic]) return randomOf(DIRECTED[topic]);
  }

  if (/\?$/.test(text.trim())) {
    if (character.personality.curiosity > 0.72) return randomOf(["maybe lol what do u think", "i dunno honestly", "depends", "probably", "not sure"]);
    if (character.personality.argumentative > 0.7) return randomOf(["nah", "nope", "probably not", "u wish lol", "depends"]);
    return randomOf(["yeah maybe", "i dunno", "probably", "not sure", "maybe"]);
  }
  return renderReaction(character, human);
}

export function normalizeLine(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\b(lol)+\b/g, "lol")
    .replace(/\s+/g, " ")
    .trim();
}

function tokenSet(text) {
  return new Set(normalizeLine(text).split(" ").filter(Boolean));
}

function jaccard(a, b) {
  const aa = tokenSet(a);
  const bb = tokenSet(b);
  if (!aa.size || !bb.size) return 0;
  let intersection = 0;
  for (const token of aa) if (bb.has(token)) intersection += 1;
  return intersection / (aa.size + bb.size - intersection);
}

export function isTooSimilar(candidate, history, speaker = "") {
  const normalized = normalizeLine(candidate);
  if (!normalized) return true;
  const recentRoom = history.slice(-100);
  const speakerLines = history.filter((m) => m.from === speaker).slice(-24);

  for (const item of recentRoom) {
    const other = normalizeLine(item.text);
    if (!other) continue;
    if (normalized === other) return true;
    if (normalized.split(" ").length <= 3 || other.split(" ").length <= 3) continue;
    if (jaccard(normalized, other) >= 0.88) return true;
  }
  for (const item of speakerLines) {
    const other = normalizeLine(item.text);
    if (!other) continue;
    if (normalized.split(" ").length > 3 && other.split(" ").length > 3 && jaccard(normalized, other) >= 0.68) return true;
  }
  return false;
}

export function chooseDistinctLine(factory, history, speaker, attempts = 24) {
  for (let i = 0; i < attempts; i += 1) {
    const candidate = factory();
    if (candidate && !isTooSimilar(candidate, history, speaker)) return candidate;
  }
  return null;
}

export function topicNamesForPrompt(text) {
  const topics = detectTopics(text);
  return topics.length ? topics.join(", ") : "none obvious";
}
